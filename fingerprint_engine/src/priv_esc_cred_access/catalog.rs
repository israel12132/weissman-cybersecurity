#[must_use]
pub fn title_for(id: u16) -> String {
    if id == 0 || id as usize > CHECK_COUNT {
        return format!("PAC-{id:03} unknown control");
    }
    let d = ((id - 1) / 50) as usize;
    let i = ((id - 1) % 50) as usize;
    format!("PAC-{id:03} {}", STEM[d][i])
}

#[must_use]
pub fn check(id: u16) -> Check {
    let domain = Domain::from_id(id);
    Check {
        id,
        domain,
        mitre: domain.mitre(),
        title: title_for(id),
    }
}

#[must_use]
pub fn all_checks() -> Vec<Check> {
    (1u16..=CHECK_COUNT as u16).map(check).collect()
}

#[must_use]
pub fn checks_for_domain(d: Domain) -> Vec<Check> {
    let start = (d as u8 as u16 - 1) * 50 + 1;
    (start..start + 50).map(check).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn catalog_is_exactly_500_unique_ids() {
        let checks = all_checks();
        assert_eq!(checks.len(), 500);
        let mut seen = std::collections::BTreeSet::new();
        let mut titles = std::collections::BTreeSet::new();
        for c in &checks {
            assert!(seen.insert(c.id), "duplicate check id {}", c.id);
            assert_eq!(c.domain, Domain::from_id(c.id));
            assert!(!c.title.is_empty());
            assert!(c.mitre.starts_with('T'));
            assert!(
                titles.insert(c.title.clone()),
                "duplicate title {}",
                c.title
            );
        }
        assert_eq!(*seen.first().unwrap(), 1);
        assert_eq!(*seen.last().unwrap(), 500);
    }
    #[test]
    fn stems_are_unique_across_the_catalog() {
        let mut titles = std::collections::BTreeSet::new();
        for (d, row) in STEM.iter().enumerate() {
            for (i, stem) in row.iter().enumerate() {
                assert!(
                    titles.insert(*stem),
                    "duplicate stem in domain {d} index {i}: {stem}"
                );
            }
        }
        assert_eq!(titles.len(), 500);
    }
    #[test]
    fn ten_domains_of_fifty() {
        for d in Domain::all() {
            assert_eq!(checks_for_domain(d).len(), 50);
        }
    }
}
